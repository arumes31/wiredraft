test("load errors recover and successful mutations are not repeated after a refresh error", async ({ page }) => {
  const options = { failReads: true, failRefresh: true };
  const { writes } = await mockAdministration(page, options);
  await page.goto("/admin.html#organizations");
  await expect(page.locator("#page-error")).toContainText("Could not load administration");
  await expect(page.locator("#administration-content")).toBeHidden();
  options.failReads = false;
  await page.getByRole("button", { name: "Try again" }).click();
  await expect(page.locator("#organizations-title")).toBeVisible();
  await page.getByRole("button", { name: "+ Add organization", exact: true }).click();
  await page.locator('#organization-form input[name="name"]').fill("Recovery lab");
  await page.getByRole("button", { name: "Create organization", exact: true }).click();
  await expect(page.locator("#page-error")).toContainText("Change saved, but the directory could not be refreshed");
  await expect(page.locator("#organization-editor")).toBeHidden();
  expect(writes).toHaveLength(1);
  options.failRefresh = false;
  await page.getByRole("button", { name: "Try again" }).click();
  await expect(page.getByRole("button", { name: "Manage Recovery lab", exact: true })).toBeVisible();
  expect(writes).toHaveLength(1);
  await page.locator(".skip-link").focus();
  await page.keyboard.press("Enter");
  await expect(page).toHaveURL(/#organizations$/);
  await expect(page.locator("#main")).toBeFocused();
});

