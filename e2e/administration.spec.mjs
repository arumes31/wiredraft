test("failed writes retain the editor and unsaved changes require confirmation", async ({ page }) => {
  await mockAdministration(page, { failWrites: true });
  await page.goto("/admin.html#organizations");
  await page.getByRole("button", { name: "Manage Lab", exact: true }).click();
  await page.locator('#organization-form input[name="name"]').fill("Renamed lab");
  await page.getByRole("button", { name: "Save name", exact: true }).click();
  await expect(page.locator("#organization-error")).toContainText("Organization contains maps");
  await expect(page.locator('#organization-form input[name="name"]')).toHaveValue("Renamed lab");
  page.once("dialog", (dialog) => dialog.dismiss());
  await page.keyboard.press("Escape");
  await expect(page.locator("#organization-editor")).toBeVisible();
  page.once("dialog", (dialog) => dialog.accept());
  await page.keyboard.press("Escape");
  await expect(page.locator("#organization-editor")).toBeHidden();
});

