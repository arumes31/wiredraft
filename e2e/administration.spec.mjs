test("administration filters users and navigates effective organization access", async ({ page }) => {
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await mockAdministration(page);
  await page.goto("/admin.html#users");
  await expect(page.locator("#user-rows tr")).toHaveCount(5);
  await expect(page.locator("#user-editor")).not.toBeVisible();
  await page.getByPlaceholder("Name or email").fill("LEA.WAGNER");
  await expect(page.locator("#user-rows tr")).toHaveCount(1);
  await page.getByRole("button", { name: "Clear filters" }).click();
  await page.locator('#user-filters select[name="status"]').selectOption("disabled");
  await expect(page.locator("#user-rows tr")).toHaveCount(1);
  await page.locator("#organizations-nav").click();
  await expect(page.locator("#organizations-title")).toBeVisible();
  await page.getByRole("button", { name: "View users with access to Vienna Operations", exact: true }).click();
  await expect(page.locator("#user-rows tr")).toHaveCount(5);
  await expect(page.locator("#organization-filter")).toHaveValue("vienna");
  await page.getByPlaceholder("Name or email").fill("no such user");
  await expect(page.locator("#users-empty")).toBeVisible();
  await page.goBack();
  await expect(page.locator("#organizations-title")).toBeVisible();
  expect(errors).toEqual([]);
});

