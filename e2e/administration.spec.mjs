  await page.locator('#user-form input[name="externalLogin"]').fill("operator@example.com");
  await page.locator('#user-form select[name="role"]').selectOption("admin");
  await expect(page.locator("#organization-grants")).toBeHidden();
  await page.getByRole("button", { name: "Create user", exact: true }).click();
  await expect(page.locator("#user-editor")).toBeHidden();
  expect(writes[1].data).toMatchObject({ authSource: "entra", externalLogin: "operator@example.com", role: "admin", allOrganizations: true, organizationIds: [] });
  expect(writes[1].data).not.toHaveProperty("password");
